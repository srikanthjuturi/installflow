/**
 * Generate `src/components/geo/indiaPaths.ts` from `@react-map/india`.
 *
 *     node scripts/gen-india-paths.mjs
 *
 * The package ships a React component, not data — the outlines live in a
 * `drawPath` object inside its bundle. We want the paths and not the component:
 * the component cannot zoom to one state, cannot take our region tokens, and
 * would tie a purely geographic constant to a React version. So the geometry is
 * extracted once, committed, and the package stays a devDependency purely so
 * this script can be re-run.
 *
 * Boundaries do not change often; when one does (a new state, a new UT), bump
 * the package and re-run this.
 */

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const SOURCE = resolve(here, "../node_modules/@react-map/india/dist/index.mjs");
const TARGET = resolve(here, "../src/components/geo/indiaPaths.ts");

/** Walks the M/L/h/l/v/z subset this data uses. Relative commands are real —
 *  a naive coordinate scan reports a bounding box that is wrong by tens of
 *  units, which would mis-centre every zoomed state. */
function bbox(d) {
  const toks = d.match(/[A-Za-z]|-?\d*\.?\d+(?:e[-+]?\d+)?/gi) ?? [];
  let i = 0, cmd = "", x = 0, y = 0, sx = 0, sy = 0;
  let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
  const num = () => parseFloat(toks[i++]);
  const mark = () => {
    if (x < minX) minX = x;
    if (y < minY) minY = y;
    if (x > maxX) maxX = x;
    if (y > maxY) maxY = y;
  };
  while (i < toks.length) {
    if (/[A-Za-z]/.test(toks[i])) cmd = toks[i++];
    if (cmd === "z" || cmd === "Z") { x = sx; y = sy; continue; }
    switch (cmd) {
      case "M": x = num(); y = num(); sx = x; sy = y; cmd = "L"; break;
      case "m": x += num(); y += num(); sx = x; sy = y; cmd = "l"; break;
      case "L": x = num(); y = num(); break;
      case "l": x += num(); y += num(); break;
      case "H": x = num(); break;
      case "h": x += num(); break;
      case "V": y = num(); break;
      case "v": y += num(); break;
      default: i++; continue;
    }
    mark();
  }
  return [round(minX), round(minY), round(maxX), round(maxY)];
}

const round = (n) => Math.round(n * 100) / 100;

const src = readFileSync(SOURCE, "utf8");
const from = src.indexOf("var drawPath");
if (from < 0) throw new Error("drawPath not found — the package layout changed");

const re = /^\s{2}"?([A-Za-z][A-Za-z &'.-]*)"?:\s*"(M[^"]+)"/gm;
const paths = {};
let m;
while ((m = re.exec(src.slice(from)))) paths[m[1]] = m[2].replace(/\\n/g, "");

const names = Object.keys(paths);
if (names.length < 36) throw new Error(`only ${names.length} outlines extracted; expected 36+`);
if (!paths["Ladakh"]) throw new Error("Ladakh missing — that is the whole reason this source was chosen");

const boxes = Object.fromEntries(names.map((n) => [n, bbox(paths[n])]));
const all = Object.values(boxes);
const world = [
  Math.min(...all.map((b) => b[0])),
  Math.min(...all.map((b) => b[1])),
  Math.max(...all.map((b) => b[2])),
  Math.max(...all.map((b) => b[3])),
];

const pkg = JSON.parse(
  readFileSync(resolve(here, "../node_modules/@react-map/india/package.json"), "utf8")
);

const out = `// GENERATED by scripts/gen-india-paths.mjs — do not edit by hand.
//
// Outlines of India's states and union territories, extracted from
// ${pkg.name}@${pkg.version} (MIT, © ${pkg.author}).
// Re-run the script rather than patching a coordinate here.
//
// This source was chosen over @svg-maps/india for one reason: it is post-2019
// and carries LADAKH as its own outline. The alternative predates the
// reorganisation, folds Ladakh into Jammu and Kashmir, and would have left a
// real state with real pincodes undrawable.
//
// It depicts India's full claimed territory — J&K and Ladakh extend through
// Gilgit-Baltistan and Aksai Chin — which is the depiction Indian law requires.

/** \`[minX, minY, maxX, maxY]\` in the shared coordinate space below. */
export type BBox = readonly [number, number, number, number];

/** The whole-country viewBox every outline is drawn in. */
export const INDIA_VIEWBOX = "${world[0]} ${world[1]} ${round(world[2] - world[0])} ${round(world[3] - world[1])}";

export const INDIA_EXTENT: BBox = [${world.join(", ")}];

/** State name -> SVG path. ${names.length} outlines. */
export const INDIA_PATHS: Record<string, string> = ${JSON.stringify(paths, null, 0)};

/** State name -> its own extent, for zooming the map to one state. */
export const STATE_BBOX: Record<string, BBox> = ${JSON.stringify(boxes, null, 0)};
`;

mkdirSync(dirname(TARGET), { recursive: true });
writeFileSync(TARGET, out);
console.log(`wrote ${TARGET}`);
console.log(`  ${names.length} outlines, viewBox "${world.join(" ")}", ${(out.length / 1024).toFixed(0)} KB`);
